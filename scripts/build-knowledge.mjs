// knowledge/*.md -> supabase/seed/knowledge.sql (idempotent upsert, run it in the SQL editor after 0013).
// A chunk whose text changed gets its embedding cleared; the `agent` function re-embeds it on next use.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { parseKnowledge } from "../supabase/functions/_shared/agent-core.js";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const f of readdirSync("knowledge").filter((x) => x.endsWith(".md") && x !== "README.md").sort()) {
  const { meta, chunks } = parseKnowledge(readFileSync(`knowledge/${f}`, "utf8"));
  for (const c of chunks) rows.push(`  (${q(c.id)}, ${q(c.source)}, ${q(c.kind)}, ${q(meta.cite)}, ${q(meta.doi)}, ${q(meta.strength)}, ${q(c.body)})`);
}

const sql = `-- Generated by scripts/build-knowledge.mjs from knowledge/*.md. Do not edit by hand.
insert into public.knowledge_chunks (id, source, kind, cite, doi, strength, body) values
${rows.join(",\n")}
on conflict (id) do update set
  source = excluded.source, kind = excluded.kind, cite = excluded.cite, doi = excluded.doi, strength = excluded.strength,
  embedding = case when public.knowledge_chunks.body = excluded.body then public.knowledge_chunks.embedding else null end,
  body = excluded.body;
`;
mkdirSync("supabase/seed", { recursive: true });
writeFileSync("supabase/seed/knowledge.sql", sql);
console.log(`${rows.length} chunks -> supabase/seed/knowledge.sql`);
